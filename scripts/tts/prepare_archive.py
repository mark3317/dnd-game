"""Record the game's exported authored phrases, then bundle WAVs and their durations."""
import argparse
import hashlib
import html
import json
from pathlib import Path
import shutil
import time
import urllib.request

ROOT = Path(__file__).resolve().parents[2]


def export_game_catalog(catalog):
    """The room authority and clients share exact asset identities and WAV durations."""
    def literal(value):
        return json.dumps(value, ensure_ascii=False).replace('$', "${'$'}")

    durations = {}
    for phrase in catalog:
        durations[phrase['text']] = max(durations.get(phrase['text'], 0), phrase['duration_ms'] + 700)
    lines = ['package ru.markn.dnd.adventure', '', '// Generated by scripts/tts/prepare_archive.py from actual Qwen recordings.',
        'internal val preparedSpeechDurations: Map<String, Long> = mapOf(']
    for text, duration in durations.items():
        lines.append(f'    {literal(text)} to {duration}L,')
    lines += [')', '', 'internal val preparedSpeechAssets: List<PreparedSpeech> = listOf(']
    for phrase in catalog:
        lines.append('    PreparedSpeech(' + ', '.join(literal(phrase[key]) for key in ('text', 'voice', 'file'))
            + f", {phrase['duration_ms']}L),")
    lines += [')', '', 'fun preparedSpeechAsset(text: String, voice: String): PreparedSpeech? =',
        '    preparedSpeechAssets.firstOrNull { it.text == text && it.voice == voice }']
    (ROOT / 'game/src/commonMain/kotlin/ru/markn/dnd/adventure/PreparedSpeechDurations.kt').write_text('\n'.join(lines) + '\n', encoding='utf-8')


def api(path, payload=None):
    data = None if payload is None else json.dumps(payload, ensure_ascii=False).encode('utf-8')
    request = urllib.request.Request('http://127.0.0.1:8091/speech/' + path, data=data,
        headers={'Content-Type': 'application/json'})
    with urllib.request.urlopen(request, timeout=10) as response:
        return json.load(response)


def generate(phrase):
    result = api('prepare', {'text': phrase['text'], 'voice': phrase['voice']})
    deadline = time.monotonic() + 600
    while result['status'] in ('queued', 'generating'):
        if time.monotonic() > deadline:
            raise RuntimeError('Generation timed out')
        time.sleep(.5)
        result = api('status/' + result['id'])
    if result['status'] != 'ready':
        raise RuntimeError('Generation failed: ' + result['id'])
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', default=str(ROOT / '.local/tts/archive-phrases.json'))
    args = parser.parse_args()
    deadline = time.monotonic() + 1200
    while api('health')['status'] != 'ready':
        if time.monotonic() > deadline:
            raise RuntimeError('Model did not become ready')
        time.sleep(2)
    phrases = json.loads(Path(args.input).read_text(encoding='utf-8'))
    output = ROOT / 'shared/src/commonMain/composeResources/files/speech'
    output.mkdir(parents=True, exist_ok=True)
    catalog, measures = [], []
    for index, phrase in enumerate(phrases):
        result = generate(phrase)
        name = result['id'] + '.wav'
        source = ROOT / '.local/tts/audio' / name
        shutil.copyfile(source, output / name)
        catalog.append({**phrase, 'file': name, 'duration_ms': result['duration_ms']})
        measures.append({'voice': phrase['voice'], **result,
            'sha256': hashlib.sha256(source.read_bytes()).hexdigest()})
        print(json.dumps({'event': 'recorded', 'index': index + 1, 'total': len(phrases), **result}), flush=True)
    (output / 'catalog.json').write_text(json.dumps(catalog, ensure_ascii=False, indent=2), encoding='utf-8')
    export_game_catalog(catalog)
    samples = [
        {'voice': 'bran', 'text': 'Всем занять оборону! Я прикрою ворота. Агата, отойдите от окна.'},
        {'voice': 'rin', 'text': 'Замок? Ну хоть кто-то в этом архиве умеет держать язык за зубами.'},
        {'voice': 'mira', 'text': 'На чертеже отмечен второй засов. Подождите, кажется, я поняла, как он устроен.'},
        {'voice': 'lada', 'text': 'Если выберемся сухими, с меня песня. Если мокрыми — две, но у камина!'},
    ]
    sample_dir = ROOT / 'assets/audio/speech-qwen-v1/samples'
    sample_dir.mkdir(parents=True, exist_ok=True)
    for phrase in samples:
        result = generate(phrase)
        shutil.copyfile(ROOT / '.local/tts/audio' / (result['id'] + '.wav'), sample_dir / (phrase['voice'] + '.wav'))
        measures.append({'sample': phrase['voice'], **result})
        print(json.dumps({'event': 'sample_recorded', 'voice': phrase['voice'], **result}), flush=True)
    evidence = ROOT / 'assets/audio/speech-qwen-v1'
    (evidence / 'manifest.json').write_text(json.dumps({'model': api('health')['model'],
        'phrases': catalog, 'measurements': measures}, ensure_ascii=False, indent=2), encoding='utf-8')
    cards = []
    for phrase in samples:
        cards.append(f'<article><h2>{html.escape(phrase["voice"])}</h2><p>{html.escape(phrase["text"])}</p><audio controls preload="none" src="samples/{phrase["voice"]}.wav"></audio></article>')
    for index, phrase in enumerate(catalog):
        cards.append(f'<article><h2>{index + 1}. {html.escape(phrase["voice"])}</h2><p>{html.escape(phrase["text"])}</p><audio controls preload="none" src="../../../shared/src/commonMain/composeResources/files/speech/{phrase["file"]}"></audio></article>')
    preview = '<!doctype html><html lang="ru"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Голоса затопленного архива</title><style>body{max-width:850px;margin:40px auto;padding:0 20px;background:#101a25;color:#e8edf0;font:18px/1.6 system-ui}h1,h2{color:#e6b66a}article{padding:20px;margin:20px 0;background:#1c2a38;border-radius:12px}audio{width:100%}h2{font-size:20px}</style><h1>Голоса затопленного архива</h1><p>Qwen3-TTS 1.7B · сначала герои, затем готовые реплики истории. Качество и характер голосов оценивает слушатель.</p>' + ''.join(cards) + '</html>'
    (evidence / 'preview.html').write_text(preview, encoding='utf-8')
    print('archive_speech_prepared', flush=True)


if __name__ == '__main__':
    main()
